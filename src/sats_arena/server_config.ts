import type { SettingsSchema } from "@settings/types";

export type HostSettings = Pick<
  SettingsSchema,
  | "satsArenaHostPort"
  | "satsArenaHostAllowRemote"
  | "satsArenaInviteCode"
  | "satsArenaWalletBackend"
  | "satsArenaSatsPerPercent"
  | "satsArenaWinSats"
  | "satsArenaMaxDepositSats"
>;

/**
 * Builds the server's TOML config. The NWC connection string is deliberately
 * left out; it's passed through SATS_ARENA_NWC_URI, not the generated TOML.
 */
export function buildServerConfig(settings: HostSettings, databasePath: string): string {
  const port = settings.satsArenaHostPort;
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error(`Invalid port: ${port}`);
  }
  if (!settings.satsArenaInviteCode.trim() || settings.satsArenaInviteCode.trim() === "change-me") {
    throw new Error("Set an invite code before starting the server");
  }
  const amounts = {
    sats_per_percent: settings.satsArenaSatsPerPercent,
    win_sats: settings.satsArenaWinSats,
    max_deposit_sats: settings.satsArenaMaxDepositSats,
  };
  for (const [name, value] of Object.entries(amounts)) {
    if (!Number.isSafeInteger(value) || value < 0) {
      throw new Error(`${name} must be a whole number of sats`);
    }
  }
  if (amounts.max_deposit_sats < 1) {
    throw new Error("max_deposit_sats must be at least 1");
  }
  if (settings.satsArenaWalletBackend !== "fake" && settings.satsArenaWalletBackend !== "nwc") {
    throw new Error("Unknown wallet backend");
  }

  const host = settings.satsArenaHostAllowRemote ? "0.0.0.0" : "127.0.0.1";
  return [
    "# Generated by the Slippi Launcher. Edits are overwritten on the next start.",
    `listen = ${tomlString(`${host}:${port}`)}`,
    `database = ${tomlString(databasePath)}`,
    `invite_code = ${tomlString(settings.satsArenaInviteCode.trim())}`,
    "",
    "[rules]",
    `sats_per_percent = ${amounts.sats_per_percent}`,
    `win_sats = ${amounts.win_sats}`,
    `max_deposit_sats = ${amounts.max_deposit_sats}`,
    "",
    "[wallet]",
    `backend = ${tomlString(settings.satsArenaWalletBackend)}`,
    "",
  ].join("\n");
}

// JSON string escapes are valid TOML basic-string escapes.
function tomlString(value: string): string {
  return JSON.stringify(value);
}
